"""K6: the code index (brief 12.2 layout, 12.7): `kb ingest repo`.

For each repository, at its pinned commit:
  files    path, language, line count, sha256, size, licence header, generated marker
  symbols  kbtool.code_symbols (C/C++ tree-sitter, Python ast, Fortran patterns)
  params   kbtool.code_params: every ParameterInput call (reads go into the `params` table)
  inputs   parameters set in AthenaK input files (athinput*), for the comparison with params
  chunks   code text by function (with the comment above it) and the rest of the file in
           windows of at most 80 lines; full-text index code_fts

Sources:
  - a manifest repository: its clone kb-data/raw/github/<owner>__<repo>/ (read as files;
    the commit comes from the clone record kb-data/meta/github/<owner>__<repo>.json and is
    checked against HEAD read as a file);
  - this repository (repo_id `local/nrpic`): athenak/src, python/nrpic and cosmo at a git
    ref of this repository (default `main`), read from git objects (`git ls-tree`,
    `git cat-file`), so the index does not depend on any worktree's uncommitted state.

Outputs: kb-data/build/code/<key>/{files,symbols,params,inputs}.jsonl and summary.json, and
the tables repos, code_files, symbols, code_chunks, code_fts, params (rows of a repository
are replaced as a whole inside the writer lock).
"""
