#!/usr/bin/env python3
"""Reports and figures of the code index (K6) and of the paper-code links (K7).

    kb/.venv/bin/python -I kb/scripts/code_report.py OUTDIR [--links-check JSON]

Reads kb-data/build/code/*/{summary.json,params.jsonl,inputs.jsonl} and
kb-data/meta/github/*.json (nothing else), writes into OUTDIR:
  code_index.md                       one row per indexed repository
  code_params.md                      parameter index of upstream AthenaK and this tree; inputs against code (P4)
  code_params_<key>.tsv               full parameter index (reads and existence checks) of AthenaK, local/nrpic
  inputs_vs_code.json                 the comparison rows
  fig_code_repos.png/.pdf             size, symbols and chunks per repository
  fig_code_params.png/.pdf            input parameters against code reads; parameters per block
"""
import argparse
import collections
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KB = os.path.dirname(HERE)
WT = os.path.dirname(KB)
sys.path.insert(0, KB)
sys.path.insert(0, os.path.join(WT, "python"))

from kbtool import code_params as P   # noqa: E402
from kbtool.paths import layout        # noqa: E402

import numpy as np                     # noqa: E402
import matplotlib.pyplot as plt        # noqa: E402
from nrpic import figstyle as fs       # noqa: E402

ROLE_ORDER = ["this", "core", "dep", "ref", "tool"]
COMPARE = [("IAS-Astrophysics__athenak", "AthenaK upstream (inputs/)"),
           ("local__nrpic", "this tree (problems/, cosmo/)"),
           ("PrincetonUniversity__athena", "Athena++ (inputs/)")]


def jl(path):
    if not os.path.exists(path):
        return []
    return [json.loads(x) for x in open(path)]


def load(lay):
    base = os.path.join(lay.build, "code")
    out = {}
    for key in sorted(os.listdir(base)):
        sp = os.path.join(base, key, "summary.json")
        if os.path.exists(sp):
            out[key] = {"summary": json.load(open(sp))}
    return out


def index_md(lay, rep):
    metas = {}
    for n in os.listdir(lay.meta_github):
        if n.endswith(".json"):
            m = json.load(open(os.path.join(lay.meta_github, n)))
            metas[n[:-5]] = m
    rows = sorted(rep.items(), key=lambda kv: (ROLE_ORDER.index(kv[1]["summary"]["role"]), kv[0].lower()))
    L = ["# Code index (K6): repositories at their pinned commits", "",
         "Generated by `kb/scripts/code_report.py` from `kb-data/build/code/*/summary.json` and the clone records",
         "`kb-data/meta/github/*.json`. Licence: from the licence file at the root (case-insensitive names); for",
         "`local/nrpic` from `athenak/LICENSE`. A repository with licence `none` or `unknown` is indexed only: no",
         "code fragment from it goes into notes (brief 12.1).", "",
         "| repository | role | commit | commit date | licence | files | lines | symbols | chunks | parameter reads |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    tot = collections.Counter()
    for key, d in rows:
        s = d["summary"]
        L.append(f"| {s['repo_id']} | {s['role']} | {str(s.get('commit_sha'))[:12]} | {str(s.get('commit_date'))[:10]} | "
                 f"{s['license_spdx']} | {s['n_files']} | {s['loc_total']} | {s['n_symbols']} | {s['n_chunks']} | "
                 f"{s.get('params_in_table', 0)} |")
        for k in ("n_files", "loc_total", "n_symbols", "n_chunks"):
            tot[k] += s[k]
        tot["params"] += s.get("params_in_table", 0)
    L.append(f"| total ({len(rows)}) | | | | | {tot['n_files']} | {tot['loc_total']} | {tot['n_symbols']} | "
             f"{tot['n_chunks']} | {tot['params']} |")
    unres = [m["repo"] for m in metas.values() if m.get("status") != "ok"]
    L += ["", f"Names of the manifest that did not resolve or failed to clone: {', '.join(unres) or 'none'}.", "",
          "Parse quality: C/C++ files with tree-sitter error nodes (symbols still extracted around them) and Python "
          "files that `ast` cannot parse (for example Python 2):", "",
          "| repository | C/C++ files with error nodes | Python parse errors |", "|---|---|---|"]
    for key, d in rows:
        s = d["summary"]
        if s.get("cpp_files_with_error_nodes") or s.get("python_parse_errors"):
            L.append(f"| {s['repo_id']} | {s.get('cpp_files_with_error_nodes', 0)} | {s.get('python_parse_errors', 0)} |")
    return "\n".join(L) + "\n", rows


def params_md(lay, rep, out):
    L = ["# Parameter index (K6, brief 12.7)", "",
         "Every call of the ParameterInput interface in the C/C++ sources (`kbtool/code_params.py`; cross-checked "
         "against a tree-sitter extractor, test P2). `access`: get = required, get_or_add = optional with the default "
         "shown, exists = `DoesParameterExist`. A block in braces is computed at run time (the expression is shown). "
         "Full tables: `code_params_<repository>.tsv` next to this file.", ""]
    comp_all = {}
    for key, label in COMPARE:
        d = os.path.join(lay.build, "code", key)
        params = jl(os.path.join(d, "params.jsonl"))
        inputs = jl(os.path.join(d, "inputs.jsonl"))
        if not params:
            continue
        reads = [p for p in params if p["access"] in ("get", "get_or_add")]
        lit = {(p["block"], p["name"]) for p in reads if p["block_literal"] and p["name_literal"]}
        L += [f"## {label}: `{rep[key]['summary']['repo_id']}` at {str(rep[key]['summary'].get('commit_sha'))[:12]}", "",
              f"- calls: {len(params)} ({', '.join(f'{k} {v}' for k, v in sorted(collections.Counter(p['access'] for p in params).items()))})",
              f"- reads (get, get_or_add): {len(reads)}; distinct literal (block, name): {len(lit)}; reads with a computed "
              f"block or name: {sum(1 for p in reads if not (p['block_literal'] and p['name_literal']))}"]
        rows = P.compare_inputs([(x["path"], x["line"], x["block"], x["name"], x["value"]) for x in inputs], reads)
        comp_all[key] = rows
        c = collections.Counter(r["status"] for r in rows)
        n = len(rows)
        if n:
            ok = c["literal"] + c["computed"]
            okp = ok + c["pattern"]
            L.append(f"- input files: {len({r['file'] for r in rows})} with {n} parameter lines; literal {c['literal']}, "
                     f"computed block {c['computed']}, computed name fitting its pattern {c['pattern']}, `<comment>` "
                     f"block {c['comment_block']}, name read under another block {c['other_block']}, unmatched "
                     f"{c['unmatched']}; literal or computed block: {ok} = {100.0 * ok / n:.1f} %; with the patterns: "
                     f"{okp} = {100.0 * okp / n:.1f} %; without the <comment> lines: "
                     f"{100.0 * okp / max(1, n - c['comment_block']):.1f} %")
            um = collections.Counter((r["block"], r["name"]) for r in rows if r["status"] in ("unmatched", "other_block"))
            L.append("")
            L.append("Unmatched lines are typing errors in input files, options that the code no longer reads, or names "
                     "built from a plain variable (no literal to match, for example `<particles> field_time1`).")
            if um:
                L += ["", "Input parameters not read with that block and name (count of input lines, first file):", "",
                      "| block | name | lines | status | first file |", "|---|---|---|---|---|"]
                first = {}
                for r in rows:
                    first.setdefault((r["block"], r["name"]), (r["file"], r["line"], r["status"]))
                for (b, nm), k in um.most_common(40):
                    f, ln, st = first[(b, nm)]
                    L.append(f"| {b} | {nm} | {k} | {st} | {f}:{ln} |")
                if len(um) > 40:
                    L.append(f"| ... | {len(um) - 40} more in inputs_vs_code.json | | | |")
        L.append("")
        tsv = os.path.join(out, f"code_params_{key}.tsv")
        with open(tsv, "w") as f:
            f.write("block\tname\ttype\taccess\tdefault\tpath\tline\tfunction\n")
            for p in sorted(params, key=lambda p: (str(p["block"]), str(p["name"]), p["path"], p["line"])):
                if p["access"] in ("get", "get_or_add", "exists"):
                    blk = p["block"] if p["block_literal"] else "{" + str(p["block"]) + "}"
                    nm = p["name"] if p["name_literal"] else "{" + str(p["name"]) + "}"
                    f.write(f"{blk}\t{nm}\t{p['type'] or ''}\t{p['access']}\t{p['default'] if p['default'] is not None else ''}"
                            f"\t{p['path']}\t{p['line']}\t{p.get('function') or ''}\n")
    # the NRPIC options of this tree
    loc = jl(os.path.join(lay.build, "code", "local__nrpic", "params.jsonl"))
    part = sorted({(p["name"], p["type"], p["access"], p["default"], p["path"], p["line"]) for p in loc
                   if p["block"] == "particles" and p["block_literal"] and p["access"] in ("get", "get_or_add")
                   and p["path"].startswith("athenak/src/particles/")}, key=lambda x: (x[0], x[4], x[5]))
    L += ["## The `<particles>` options of the NRPIC module (this tree, athenak/src/particles)", "",
          "| name | type | access | default | read at |", "|---|---|---|---|---|"]
    for nm, ty, acc, de, pth, ln in part:
        L.append(f"| {nm} | {ty} | {acc} | {'' if de is None else de} | {pth.replace('athenak/src/', '')}:{ln} |")
    with open(os.path.join(out, "inputs_vs_code.json"), "w") as f:
        json.dump(comp_all, f, indent=0)
    return "\n".join(L) + "\n", comp_all


def fig_repos(rows, path):
    fs.use_style()
    names = [d["summary"]["repo_id"] for _, d in rows]
    loc = np.array([d["summary"]["loc_total"] for _, d in rows], float)
    syms = np.array([d["summary"]["n_symbols"] for _, d in rows], float)
    chunks = np.array([d["summary"]["n_chunks"] for _, d in rows], float)
    roles = [d["summary"]["role"] for _, d in rows]
    col = {"this": fs.PAL["red"], "core": fs.PAL["blue"], "dep": fs.PAL["yellow"], "ref": fs.PAL["green"],
           "tool": "grey"}
    n = len(names)
    H = 0.13 * n + 1.5
    fig = plt.figure(figsize=(fs.FULL_WIDTH, H))
    h = (0.13 * n) / H
    ax1 = fig.add_axes([0.30, 0.75 / H, 0.32, h])
    ax2 = fig.add_axes([0.65, 0.75 / H, 0.32, h], sharey=ax1)
    y = np.arange(n)[::-1]
    ax1.barh(y, loc, color=[col[r] for r in roles], height=0.75)
    ax1.set_xscale("log")
    ax1.set_xlabel("lines in the checkout")
    ax1.set_yticks(y)
    ax1.set_yticklabels(names, fontsize=5.5)
    ax1.tick_params(axis="y", which="minor", left=False, right=False)
    ax2.scatter(syms + 0.5, y, s=6, color=fs.PAL["blue"], label="symbols", zorder=3)
    ax2.scatter(chunks + 0.5, y, s=6, marker="s", facecolor="none", edgecolor=fs.PAL["red"], lw=0.7,
                label="chunks (full text)", zorder=3)
    ax2.set_xscale("log")
    ax2.set_xlabel("count (+0.5)")
    ax2.tick_params(axis="y", which="both", labelleft=False)
    from matplotlib.patches import Patch
    ax1.legend(handles=[Patch(color=c, label=f"role {r}") for r, c in col.items()], loc="lower left",
               bbox_to_anchor=(0.0, 1.0), fontsize=6.5, ncol=3, handlelength=1.0, columnspacing=0.8)
    ax2.legend(loc="lower left", bbox_to_anchor=(0.0, 1.0), fontsize=6.5, ncol=1)
    ax1.set_ylim(-0.7, n - 0.3)
    fs.save(fig, path)
    plt.close(fig)


def fig_params(lay, comp_all, path):
    fs.use_style()
    fig = plt.figure(figsize=(fs.FULL_WIDTH, 3.4))
    ax = fig.add_axes([0.08, 0.17, 0.42, 0.72])
    keys = [k for k, _ in COMPARE if comp_all.get(k)]
    sts = [("literal", fs.PAL["blue"]), ("computed", fs.PAL["green"]), ("pattern", fs.PAL["orange"]),
           ("comment_block", "lightgrey"), ("other_block", fs.PAL["yellow"]), ("unmatched", fs.PAL["red"])]
    x = np.arange(len(keys))
    bottom = np.zeros(len(keys))
    for st, c in sts:
        v = np.array([sum(1 for r in comp_all[k] if r["status"] == st) / len(comp_all[k]) for k in keys])
        ax.bar(x, v, bottom=bottom, color=c, width=0.6, label=st.replace("_", " "))
        bottom += v
    ax.axhline(0.9, **fs.GUIDE)
    ax.text(-0.45, 0.885, "P4 threshold 0.9", ha="left", va="top", fontsize=7)
    ax.set_xticks(x)
    ax.set_xticklabels([{"IAS-Astrophysics__athenak": "AthenaK\nupstream", "local__nrpic": "this\ntree",
                         "PrincetonUniversity__athena": "Athena++"}[k] for k in keys])
    ax.tick_params(axis="x", which="minor", bottom=False, top=False)
    ax.set_ylabel("fraction of input-file parameter lines")
    ax.set_ylim(0, 1.0)
    ax.set_xlim(-0.5, len(keys) + 0.9)
    ax.legend(loc="center right", fontsize=7, ncol=1, handlelength=1.0)
    ax2 = fig.add_axes([0.64, 0.17, 0.33, 0.72])
    for key, colr, lab, dy in (("IAS-Astrophysics__athenak", fs.PAL["blue"], "AthenaK upstream", -0.2),
                               ("local__nrpic", fs.PAL["red"], "this tree", 0.2)):
        ps = [p for p in jl(os.path.join(lay.build, "code", key, "params.jsonl"))
              if p["access"] in ("get", "get_or_add") and p["block_literal"]]
        c = collections.Counter(p["block"] for p in ps)
        if key == "local__nrpic":
            order = [b for b, _ in c.most_common(14)]
        ax2.__dict__.setdefault("_c", {})[key] = (c, colr, lab, dy)
    for key, (c, colr, lab, dy) in ax2._c.items():
        yy = np.arange(len(order))[::-1]
        ax2.barh(yy + dy, [c.get(b, 0) for b in order], height=0.4, color=colr, label=lab)
    ax2.set_yticks(np.arange(len(order))[::-1])
    ax2.set_yticklabels(order, fontsize=7)
    ax2.tick_params(axis="y", which="minor", left=False, right=False)
    ax2.set_xlabel("parameter reads with a literal block")
    ax2.legend(loc="lower right", fontsize=7)
    fs.save(fig, path)
    plt.close(fig)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("outdir")
    a = ap.parse_args()
    lay = layout()
    os.makedirs(a.outdir, exist_ok=True)
    rep = load(lay)
    md, rows = index_md(lay, rep)
    open(os.path.join(a.outdir, "code_index.md"), "w").write(md)
    md2, comp = params_md(lay, rep, a.outdir)
    open(os.path.join(a.outdir, "code_params.md"), "w").write(md2)
    fig_repos(rows, os.path.join(a.outdir, "fig_code_repos"))
    fig_params(lay, comp, os.path.join(a.outdir, "fig_code_params"))
    summ = {k: collections.Counter(r["status"] for r in v) for k, v in comp.items()}
    print(json.dumps({"repos": len(rows), "inputs_vs_code": summ}))


if __name__ == "__main__":
    main()
