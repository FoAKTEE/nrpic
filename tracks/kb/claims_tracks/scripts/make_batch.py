#!/usr/bin/env python3
"""Turn a decisions table into the shell script of one registered batch run.

    python3 -I tracks/kb/claims_tracks/scripts/make_batch.py decisions/<name>.tsv

decisions/<name>.tsv columns (tab-separated, '#' lines skipped):
    claim_id  action  locator  evidence  reason
action is one of
    verify       kb claim verify ID --evidence E            (the claim's own locator was read)
    verify_loc   kb claim verify ID --evidence E --locator L (locator corrected: case c)
    refute       kb claim refute ID --evidence E
    relocate     kb claim relocate ID --locator L --evidence E (label kept)
    keep         annotation only: stays to_verify, the reason recorded (case d)
    annotate     annotation only: judgement or background (case e), or extra evidence
    refresh      status refresh of a hand-added claim (annotate.py refresh), then annotation
Writes scripts/batch_<name>.sh and decisions/<name>_annot.tsv (the annotation rows). The shell
script runs every command, records failures, re-checks with `kb claim check --id` only the
seeded claims verified at their own locator (a check after a relocation would put the note's
old locator rows back; JOURNAL.md, start), and writes the ledger rows of the run into
$NRPIC_RUN_DIR (ledger.py).
"""
import csv
import os
import shlex
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PKG = os.path.dirname(HERE)
BY = "kb-claims_tracks"
KB = "/usr/bin/python3 -I kb/bin/kb"
BASELINE = "/data/haiyangw/nrpic/scratch/kb/kb-20261120-222240-f9db7eb/counts.json"


def read(path):
    rows = []
    with open(path) as f:
        for line in f:
            if not line.strip() or line.startswith("#"):
                continue
            parts = line.rstrip("\n").split("\t")
            parts += [""] * (5 - len(parts))
            cid, action, loc, ev, reason = parts[:5]
            rows.append({"id": int(cid), "action": action.strip(), "loc": loc.strip(), "ev": ev.strip(),
                         "reason": reason.strip()})
    return rows


def main():
    dec = os.path.abspath(sys.argv[1])
    name = os.path.splitext(os.path.basename(dec))[0]
    rows = read(dec)
    q = shlex.quote
    rel = os.path.relpath(dec, os.path.dirname(os.path.dirname(os.path.dirname(PKG))))
    ann_path = os.path.join(os.path.dirname(dec), f"{name}_annot.tsv")
    ann_rel = os.path.relpath(ann_path, os.path.dirname(os.path.dirname(os.path.dirname(PKG))))
    lines = ["#!/bin/bash",
             f"# batch {name}: generated by scripts/make_batch.py from {rel}; do not edit by hand",
             "cd /data/haiyangw/nrpic/wt/kb || exit 2",
             "fail=0", "test -n \"${NRPIC_RUN_DIR:-}\" || { echo 'not inside nrpic-run'; exit 2; }",
             f"python3 -I tracks/kb/claims_tracks/scripts/ledger.py snapshot {q(rel)} > \"$NRPIC_RUN_DIR/before.json\" || fail=1"]
    ann, check, refresh = [], [], []
    for r in rows:
        cid, a = r["id"], r["action"]
        ev = r["ev"]
        if a == "verify":
            lines.append(f"{KB} claim verify {cid} --by {BY} --evidence {q(ev)} || {{ echo FAILED {cid}; fail=1; }}")
            check.append(cid)
        elif a == "verify_loc":
            lines.append(f"{KB} claim verify {cid} --by {BY} --evidence {q(ev)} --locator {q(r['loc'])} "
                         f"|| {{ echo FAILED {cid}; fail=1; }}")
        elif a == "refute":
            lines.append(f"{KB} claim refute {cid} --by {BY} --evidence {q(ev)} || {{ echo FAILED {cid}; fail=1; }}")
        elif a == "relocate":
            lines.append(f"{KB} claim relocate {cid} --by {BY} --locator {q(r['loc'])} --evidence {q(ev)} "
                         f"|| {{ echo FAILED {cid}; fail=1; }}")
            ann.append((cid, ev))
        elif a in ("keep", "annotate"):
            ann.append((cid, ev))
        elif a == "refresh":
            refresh.append(cid)
            if ev:
                ann.append((cid, ev))
        else:
            raise SystemExit(f"unknown action {a!r} for claim {cid}")
    with open(ann_path, "w") as f:
        f.write(f"# annotations of batch {name} (claim_id TAB evidence)\n")
        for cid, ev in ann:
            f.write(f"{cid}\t{ev}\n")
    if refresh:
        lines.append(f"python3 -I tracks/kb/claims_tracks/scripts/annotate.py refresh {' '.join(map(str, refresh))} "
                     "|| { echo FAILED refresh; fail=1; }")
    if ann:
        lines.append(f"python3 -I tracks/kb/claims_tracks/scripts/annotate.py annotate {q(ann_rel)} "
                     "|| { echo FAILED annotate; fail=1; }")
    if check:
        lines.append(f"{KB} claim check --id {' '.join(map(str, check))} --by {BY} || {{ echo FAILED check; fail=1; }}")
    lines.append(f"python3 -I tracks/kb/claims_tracks/scripts/ledger.py rows {q(rel)} \"$NRPIC_RUN_DIR/before.json\" "
                 f"\"$NRPIC_RUN_ID\" > \"$NRPIC_RUN_DIR/ledger_rows.tsv\" || fail=1")
    lines.append("exit $fail")
    out = os.path.join(HERE, f"batch_{name}.sh")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    os.chmod(out, 0o755)
    print(f"{out}: {len(rows)} decisions ({sum(1 for r in rows if r['action'].startswith('verify'))} verify, "
          f"{sum(1 for r in rows if r['action'] == 'refute')} refute, {len(ann)} annotations, "
          f"{len(check)} re-checked)")


if __name__ == "__main__":
    main()
