#!/usr/bin/env python3
"""Write the database commands of step 2 from plan_seeds.tsv (package claims_brief).

  apply.sh       `kb claim verify` and `kb claim refute` per seed (each takes the writer lock)
                 and one `kb claim seed-brief --annotate annotate.tsv`
  annotate.tsv   claim_id TAB evidence TAB status, for the seeds whose label stays

Usage: python3 -I gen_apply.py PLAN_SEEDS_TSV OUTDIR
The commands are run from the worktree root (kb/.venv/bin/python -I kb/bin/kb ...).
"""
import csv
import os
import shlex
import sys

REF = "kb/brief-check 476a1763"
BY = "kb-claims_brief"
REVIEW = "review sample 30/30 agree (tracks/kb/claims_brief/REVIEW_SAMPLE.md)"
KB = "kb/.venv/bin/python -I kb/bin/kb"


def main():
    plan, out = sys.argv[1], sys.argv[2]
    os.makedirs(out, exist_ok=True)
    rows = list(csv.DictReader(open(plan, encoding="utf-8"), delimiter="\t"))
    sh = ["#!/bin/bash", "# generated by gen_apply.py from " + plan, "set -u", "rc=0"]
    ann = []
    for r in rows:
        cid, act = r["claim_id"], r["action"]
        base = f"brief check ({REF}): {r['evidence_rows']}; verdicts {r['verdicts']}"
        if act == "verify":
            ev = f"{base}; {REVIEW}"
            sh.append(f"{KB} claim verify {cid} --by {BY} --evidence {shlex.quote(ev)} "
                      f"--locator {shlex.quote(r['locator'])} || rc=1")
        elif act == "refute":
            ev = (f"{base}; {r['why']}; errata rows {r['errata'] or '-'} (provisional {r['errata_prov'] or '-'})"
                  f"; counter-evidence {r['locator'] or '-'}; {REVIEW}")
            sh.append(f"{KB} claim refute {cid} --by {BY} --evidence {shlex.quote(ev)} || rc=1")
        else:
            status = "partial" if act == "annotate-partial" else "located"
            ann.append((cid, f"{base}; label unchanged: {r['why']}", status))
    with open(os.path.join(out, "annotate.tsv"), "w") as f:
        f.write("# claim_id\tevidence\tstatus\n")
        for cid, ev, st in ann:
            f.write(f"{cid}\t{ev.replace(chr(9), ' ')}\t{st}\n")
    sh.append(f"{KB} claim seed-brief --annotate {shlex.quote(os.path.join(out, 'annotate.tsv'))} || rc=1")
    sh.append("exit $rc")
    open(os.path.join(out, "apply.sh"), "w").write("\n".join(sh) + "\n")
    print(f"verify {sum(1 for r in rows if r['action'] == 'verify')}, refute "
          f"{sum(1 for r in rows if r['action'] == 'refute')}, annotate {len(ann)}")


if __name__ == "__main__":
    main()
