#!/usr/bin/env python3
"""Input and mode file of a slow-roll scouting case that the release executable can run
without the perturbed initial slice of SPEC 5.3 (request R8, not implemented): start from
the homogeneous slice (`pgen scalar_field`, `id = flrw`) dn_pre e-folds BEFORE the lowest
lattice mode reaches the window (W(k_min) ~ exp(-2 s dn_pre) at the start), and let the
Mukhanov-Sasaki sources (`noise = mukhanov_sasaki`, level 0, stencil projector) bring
every mode in. Units G = c = 1, geodesic slicing, a = 1 and H ~ 1 at the start.

Background: V = m^2 phi^2/2 with phi0 = 2.75 (eps1 = 1/(4 pi phi^2) = 0.0105 at the
start, the SR case's eps1 ~ 0.011 at N*, spec/SPEC.md section 6), m such that the
slow-roll H is 1 at the start, Pi0 = -V'/(3H). Box: L = 2 pi/(sigma a* H*) with a*, H*
the Friedmann values dn_pre e-folds after the start (the lowest shell is half in at t*,
as in SPEC 5.2). Modes: |n|^2 <= (N/4)^2 (k_max = N k_sigma*/4). Mode functions at t = 0:
the de Sitter Bunch-Davies form with the start's H and Pi, R = lam (H/Pi) dphi_k,
dphi_k = e^{-ik tau}(1 - i/(k tau))/(a sqrt(2k)), tau = -1/(aH); lam scales the amplitude
to Delta_R ~ 1e-6 (the physical 2e-9 would leave gt - delta below float precision in the
bin output used for the gt term). Any pair (R, dR/dt) is valid data of the mode equation,
so the reference for the NR fields is the code's own lockstep R_q (and SciPy's).

    make_sr_case.py --N 32 --out DIR [--dn-pre 1.5] [--nf 8.0] [--pi-sign 1]
Writes DIR/sr.athinput, DIR/modes.txt, DIR/case.json.
"""
import argparse
import json
import os
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, ".."))
import sfa  # noqa: E402
from nrpic import scalar_field as nsf  # noqa: E402

TEMPLATE = """# Slow-roll scouting case without the perturbed initial slice (generated by
# tracks/E-stoch-inf/analysis/scripts/make_sr_case.py; see its docstring).
<comment>
problem   = slow roll from a homogeneous slice, Mukhanov-Sasaki sources

<job>
basename  = sr
rng_seed  = {seed}

<mesh>
nghost    = 4
nx1       = {N}
x1min     = 0.0
x1max     = {L:.17e}
ix1_bc    = periodic
ox1_bc    = periodic
nx2       = {N}
x2min     = 0.0
x2max     = {L:.17e}
ix2_bc    = periodic
ox2_bc    = periodic
nx3       = {N}
x3min     = 0.0
x3max     = {L:.17e}
ix3_bc    = periodic
ox3_bc    = periodic

<meshblock>
nx1       = {mb}
nx2       = {mb}
nx3       = {mb}

<time>
evolution  = dynamic
integrator = rk4
cfl_number = 0.25
nlim       = -1
tlim       = {tlim:.17e}
ndiag      = 100

<z4c>
lapse_oplog     = 0.0     # geodesic slicing, zero shift (SPEC section 4)
lapse_harmonic  = 0.0
lapse_advect    = 0.0
shift_Gamma     = 0.0
shift_eta       = 0.0
shift_advect    = 0.0
diss            = 0.0
damp_kappa1     = 0.0
damp_kappa2     = 0.0
excise_chi      = 0.0

<scalar_field>
couple          = true
potential       = quadratic
mass            = {m:.17e}
diss            = 0.0
hist_dcycle     = 1
dump_dt         = {ddt:.17e}
noise           = mukhanov_sasaki
noise_nmax2     = {nmax2}
noise_sharpness = 5.0
noise_sigma     = 1.0
noise_level     = 0
noise_projector = stencil
noise_kick_pi   = true
noise_kick_k    = true
noise_kick_a    = true
noise_pi_sign   = {pisign}
noise_mode_file = modes.txt

<problem>
pgen_name  = scalar_field
id         = flrw
phi0       = {phi0:.17e}
pi0        = {pi0:.17e}

<output1>
file_type  = bin
variable   = z4c
dt         = {ddt:.17e}
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--N", type=int, required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--dn-pre", type=float, default=1.5)
    ap.add_argument("--nf", type=float, default=8.0, help="ln a at the end")
    ap.add_argument("--pi-sign", type=float, default=1.0)
    ap.add_argument("--delta-r", type=float, default=1e-6, help="target Delta_R")
    ap.add_argument("--seed", type=int, default=20261115)
    ap.add_argument("--meshblock", type=int, default=0)
    a = ap.parse_args()
    phi0 = 2.75
    m = 1.0 / (phi0 * np.sqrt(4.0 * np.pi / 3.0))
    v, dv = nsf.potential("quadratic", mass=m)
    pi0 = -dv(phi0) / 3.0                                       # slow-roll velocity, H ~ 1
    t = np.linspace(0.0, 12.0, 24001)
    bg = nsf.friedmann(v, dv, phi0, pi0, t)
    tstar = np.interp(a.dn_pre, bg["ln_a"], bg["time"])
    hstar = np.interp(tstar, bg["time"], bg["H"])
    tf = np.interp(a.nf, bg["ln_a"], bg["time"])
    L = 2.0 * np.pi / (np.exp(a.dn_pre) * hstar)
    nmax = a.N // 4
    nmax2 = nmax * nmax
    shells = np.unique(nsf.mode_set(nmax2)[1])
    k = 2.0 * np.pi * np.sqrt(shells) / L
    h0, pib = bg["H"][0], pi0
    eps1 = 4 * np.pi * pib ** 2 / h0 ** 2
    unscaled = h0 ** 2 / (np.pi * eps1)              # Delta_R = H^2/(8 pi^2 eps1 Mpl^2), Mpl^2 = 1/(8 pi)
    lam = np.sqrt(a.delta_r / unscaled)
    tau = -1.0 / h0
    c = lam * (h0 / pib) / np.sqrt(2.0 * k)
    r0 = -c * h0 * (tau - 1j / k) * np.exp(-1j * k * tau)
    dr0 = -1j * c * h0 ** 2 * k * tau ** 2 * np.exp(-1j * k * tau)
    os.makedirs(a.out, exist_ok=True)
    np.savetxt(os.path.join(a.out, "modes.txt"),
               np.column_stack([shells, r0.real, r0.imag, dr0.real, dr0.imag]),
               fmt=["%d", "%.17e", "%.17e", "%.17e", "%.17e"],
               header="n2 Re_R Im_R Re_dR Im_dR at t = 0 (de Sitter Bunch-Davies form, scaled)")
    mb = a.meshblock or a.N
    ddt = 0.25 / hstar
    with open(os.path.join(a.out, "sr.athinput"), "w") as f:
        f.write(TEMPLATE.format(seed=a.seed, N=a.N, L=L, mb=mb, tlim=tf, m=m, ddt=ddt,
                                nmax2=nmax2, pisign=a.pi_sign, phi0=phi0, pi0=pi0))
    case = dict(N=a.N, L=L, phi0=phi0, pi0=pi0, mass=m, dn_pre=a.dn_pre, nf=a.nf,
                tstar=tstar, hstar=hstar, tlim=tf, nmax2=nmax2, lam=lam, eps1_start=eps1,
                H_start=h0, dump_dt=ddt, pi_sign=a.pi_sign, seed=a.seed,
                W_kmin_start=float(sfa.window(2 * np.pi / L, 1.0, h0)),
                steps_estimate=tf / (0.25 * L / a.N))
    with open(os.path.join(a.out, "case.json"), "w") as f:
        json.dump(case, f, indent=1)
    print(json.dumps(case, indent=1))


if __name__ == "__main__":
    main()
