#!/usr/bin/env python3
"""Input files of the noise unit test U1-U8 (tracks/E-stoch-inf/noise/NOISE_SPEC.md
section 9) at the base size, one file per variant, from the lead's base input
(analysis/lead/inputs/u_base.athinput: N = 64, nmax2 = 256, 300 steps, dumps every 100
cycles, restart file every 150). The variants are those of analysis/lead/u_runs.py
(same function, imported), so a variant differs from the base only in the options named
there. U4 is U2 restarted from its restart file at cycle 150 (no input of its own);
U9 is U2 on a card (same input as U2).

    python3 make_u_inputs.py --base BASE --out DIR [--u5-nmax2 64]
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, "..", "lead"))
from u_runs import edit_input, variants  # noqa: E402


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--u5-nmax2", type=int, default=64)
    a = ap.parse_args()
    base = open(a.base).read()
    n = int(re.search(r"<mesh>[^<]*?\bnx1\s*=\s*(\d+)", base).group(1))
    cfl = float(re.search(r"cfl_number\s*=\s*([0-9.eE+-]+)", base).group(1))
    os.makedirs(a.out, exist_ok=True)
    head = (f"# Generated by tracks/E-stoch-inf/analysis/scripts/make_u_inputs.py from "
            f"{os.path.relpath(a.base, os.path.join(HERE, '..', '..', '..', '..'))}\n")
    for name, ch in variants(n, cfl, a.u5_nmax2).items():
        with open(os.path.join(a.out, f"{name}.athinput"), "w") as f:
            f.write(head + "# variant " + name + ": " +
                    (", ".join(f"{b}/{k} = {v}" for (b, k), v in ch.items()) or "base") + "\n")
            f.write(edit_input(base, ch))
        print(name, ch)


if __name__ == "__main__":
    main()
