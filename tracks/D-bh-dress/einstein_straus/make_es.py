def fig_profiles(model, path):
    fs.use_style()
    import matplotlib.pyplot as plt
    rb = np.geomspace(0.05, 1.5 * model.Rout, 4000)
    p = model.profiles(rb)
    fig, axs = plt.subplots(3, 1, figsize=(fs.FULL_WIDTH, 8.0), sharex=True)
    fig.subplots_adjust(left=0.1, right=0.97, bottom=0.07, top=0.97, hspace=0.06)
    ax = axs[0]
    ax.plot(rb, p["psi"], color=fs.PAL["blue"], label=r"$\psi$ (full)")
    ax.plot(rb, 1.0 + p["u"], color=fs.PAL["red"], label=r"$1 + u$ (table)")
    ax.plot(rb, p["alpha"], color=fs.PAL["yellow"], label=r"$\alpha = \psi^{-2}$")
    ax.plot(rb, p["W"], color=fs.PAL["green"], ls="--", label=r"$dR/dl$")
    ax.plot(rb, p["f"], color="k", ls=":", label=r"$f$")
    ax.set_ylim(-1.1, 3.0)
    ax.set_ylabel("dimensionless")
    ax.legend(loc="upper right", ncol=2)
    ax = axs[1]
    Hr = model.H
    ax.plot(rb, p["KT"] / Hr, color=fs.PAL["blue"], label=r"$K_T/H$")
    ax.plot(rb, p["KL"] / Hr, color=fs.PAL["red"], label=r"$K_L/H$")
    ax.plot(rb, p["betar"], color=fs.PAL["yellow"], label=r"$\beta^{\bar r}$ (table column)")
    ax.axhline(0.0, **fs.THIN)
    ax.set_ylabel(r"$K/H$, $\beta^{\bar r}$")
    ax.set_ylim(-2.2, 1.0)
    ax.legend(loc="lower left", ncol=3)
    ax = axs[2]
    ax.plot(rb, p["m"], color=fs.PAL["blue"], label=r"Misner-Sharp $m$")
    ax.plot(rb, p["rho"] / model.rho0 * model.Mtot, color=fs.PAL["red"],
            label=r"$\rho/\rho_0 \times M_{\rm tot}$")
    ax.plot(rb, np.where(np.isfinite(p["R"]), p["R"] / rb, np.nan), color=fs.PAL["yellow"],
            label=r"$R/\bar r = \psi^2$")
    ax.set_yscale("log")
    ax.set_ylim(0.5, 60.0)
    ax.set_ylabel(r"$m/M$, $R/\bar r$")
    ax.legend(loc="upper left", ncol=3)
    for a in axs:
        for x in (model.rbar_throat, model.rbar0, model.R1, model.Rw, model.Rb, model.Rout):
            a.axvline(x, **fs.MASK_LINE)
    for x, lab in ((model.rbar_throat, "throat"), (model.rbar0, r"$R_0$"),
                   (model.R1, r"$R_1 = R_{\rm in}$"), (model.Rw, r"$R_w$"), (model.Rb, r"$R_b$")):
        axs[1].text(x * 1.04, 0.75, lab, fontsize=8, rotation=90, va="top")
    axs[2].set_xscale("log")
    axs[2].set_xlabel(r"$\bar r / M$")
    fs.save(fig, path)


def fig_expansions(model, path):
    fs.use_style()
    import matplotlib.pyplot as plt
    rb = np.geomspace(0.05, 1.5 * model.Rout, 4000)
    thp, thm = model.expansions(rb)
    p = model.profiles(rb)
    R = p["R"]
    fig, axs = plt.subplots(1, 2, figsize=(fs.FULL_WIDTH, 3.4))
    fig.subplots_adjust(left=0.09, right=0.98, bottom=0.15, top=0.95, wspace=0.28)
    ax = axs[0]
    ax.plot(rb, R * thp / 2, color=fs.PAL["red"], label=r"$R\,\theta_+/2$ (towards larger $\bar r$)")
    ax.plot(rb, R * thm / 2, color=fs.PAL["blue"], label=r"$R\,\theta_-/2$")
    ax.axhline(0.0, **fs.THIN)
    ax.axvline(model.rbar_throat, **fs.MASK_LINE)
    ax.set_xscale("log")
    ax.set_xlabel(r"$\bar r/M$")
    ax.set_ylabel(r"$R\,\theta/2$")
    ax.legend(loc="upper left")
    ax.text(0.40, 0.42, "anti-trapped (both > 0): nowhere", transform=ax.transAxes, fontsize=8)
    ax = axs[1]
    prod = R * R * thp * thm / 4
    ax.plot(rb, prod, color=fs.PAL["red"], label=r"$R^2\theta_+\theta_-/4$")
    ax.plot(rb, -(1 - 2 * p["m"] / R), **dict(fs.GUIDE, label=r"$-(1 - 2m/R)$"))
    ax.set_xscale("log")
    ax.set_xlabel(r"$\bar r/M$")
    ax.legend(loc="upper right")
    ax.axvline(model.rbar_throat, **fs.MASK_LINE)
    fs.save(fig, path)


def reference_curves(model, Rt, tau):
    cols = {"tau": tau}
    cols["R_wall"] = model.radius(np.full_like(tau, model.Rin), tau)
    cols["R_schuecking"] = model.radius(np.full_like(tau, model.Rw), tau)
    cols["R_outer"] = model.radius(np.full_like(tau, model.Rout), tau)
    cols["a_plateau"] = model.scale_factor(tau)
    cols["m_inside_wall"] = np.full_like(tau, model.M)
    for i, R0 in enumerate(Rt):
        cols[f"R_tracer{i}"] = model.radius(np.full_like(tau, R0), tau)
    return cols


def fig_reference(model, cols, Rt, path):
    fs.use_style()
    import matplotlib.pyplot as plt
    tau = cols["tau"]
    fig, axs = plt.subplots(2, 1, figsize=(fs.COLUMN_WIDTH * 1.5, 5.6), sharex=True,
                            gridspec_kw=dict(height_ratios=[3, 1]))
    fig.subplots_adjust(left=0.15, right=0.97, bottom=0.09, top=0.97, hspace=0.05)
    ax = axs[0]
    cc = fs.series_colors(len(Rt))
    for i, (R0, c) in enumerate(zip(Rt, cc)):
        ax.plot(tau, cols[f"R_tracer{i}"], color=c, lw=1.0)
    ax.plot(tau, cols["R_wall"], color=fs.PAL["red"], lw=2.0, label="wall (innermost dust)")
    ax.plot(tau, cols["R_outer"], color=fs.PAL["blue"], lw=2.0, label="outermost dust")
    ax.plot(tau, model.Rw * cols["a_plateau"], **dict(fs.GUIDE, label=r"$R_w\,a(\tau)$, EdS"))
    ax.axhline(2 * model.M, **fs.MASK_LINE)
    ax.set_yscale("log")
    ax.set_ylabel(r"areal radius $R/M$")
    ax.set_ylim(1.0, 600)
    ax.legend(loc="lower right")
    ax.text(0.02, 0.92, "thin: tracers at rest in the slice", transform=ax.transAxes, fontsize=8)
    ax = axs[1]
    ax.plot(tau, cols["m_inside_wall"], color=fs.PAL["red"], label=r"$m$ inside the wall")
    ax.set_ylim(0.9, 1.1)
    ax.set_ylabel(r"$m/M$")
    ax.set_xlabel(r"proper time $\tau/M$")
    ax.legend(loc="upper right")
    fs.save(fig, path)


def fig_particles(model, x, mp, hp, path):
    fs.use_style()
    import matplotlib.pyplot as plt
    r = np.linalg.norm(x, axis=1)
    edges = np.arange(model.Rin - 2 * hp, model.Rout + 4 * hp, hp)
    cum = np.array([mp[r < e].sum() for e in edges])
    fig, axs = plt.subplots(2, 1, figsize=(fs.COLUMN_WIDTH * 1.5, 5.0), sharex=True)
    fig.subplots_adjust(left=0.16, right=0.97, bottom=0.1, top=0.97, hspace=0.05)
    ax = axs[0]
    ax.plot(edges, model.M + cum, color=fs.PAL["red"], label="lattice")
    rr = np.linspace(edges[0], edges[-1], 1000)
    ax.plot(rr, model.mass(rr), **dict(fs.GUIDE, label=r"continuum $m(R)$"))
    ax.set_ylabel(r"$M + $ dust mass inside $R$")
    ax.legend(loc="upper left")
    ax = axs[1]
    ax.plot(edges, (model.M + cum) / model.mass(edges) - 1.0, color=fs.PAL["red"])
    ax.axhline(0.0, **fs.THIN)
    ax.set_ylabel("relative difference")
    ax.set_xlabel(r"$\bar r = R$ (flat in the dust) $/M$")
    fs.save(fig, path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", required=True)
    ap.add_argument("--M", type=float, default=1.0)
    ap.add_argument("--Rw", type=float, default=40.0)
    ap.add_argument("--w_in", type=float, default=4.0)
    ap.add_argument("--Rb", type=float, default=100.0)
    ap.add_argument("--w_out", type=float, default=6.0)
    ap.add_argument("--R0", type=float, default=4.0)
    ap.add_argument("--R1", type=float, default=None)
    ap.add_argument("--drbar", type=float, default=0.02)
    ap.add_argument("--hp", type=float, default=2.0, help="particle lattice spacing")
    ap.add_argument("--tau_max", type=float, default=400.0)
    ap.add_argument("--no_figs", action="store_true")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    model = em.EinsteinStrausBH(M=a.M, Rw=a.Rw, w_in=a.w_in, Rb=a.Rb, w_out=a.w_out, R0=a.R0, R1=a.R1)
    s = model.summary()
    # table
    tab = model.table(drbar=a.drbar)
    ptab = os.path.join(a.out, "es.tab")
    hdr = ["black hole in a vacuum bubble inside an expanding dust ball (Einstein-Straus type), "
           "tracks/D-bh-dress/einstein_straus/make_es.py",
           "add a puncture component of bare mass m_p at the same centre"]
    hdr += [f"{k} = {v!r}" for k, v in s.items()]
    em.write_tab2(ptab, tab, header=hdr)
    # particles
    xt, Rt, rbt, mt, Et, _ = tracers(model)
    xd, md = model.lattice(a.hp)
    x = np.concatenate([xt, xd])
    m = np.concatenate([np.full(len(xt), 1.0e-30), md])
    pnrp = os.path.join(a.out, "es.nrp")
    em.write_nrp(pnrp, x, np.zeros_like(x), m)
    # reference curves
    tau = np.linspace(0.0, a.tau_max, 2001)
    cols = reference_curves(model, Rt, tau)
    pref = os.path.join(a.out, "es_reference.csv")
    keys = list(cols)
    np.savetxt(pref, np.column_stack([cols[k] for k in keys]), delimiter=",",
               header=",".join(keys), comments="# ", fmt="%.15e")
    # input
    pin = os.path.join(a.out, "es.athinput")
    with open(pin, "w") as fo:
        fo.write(ATHINPUT.format(m_p=model.m_p, M=model.M, u0=model.u0, tlim=float(a.tau_max),
                                 r_ah=round(1.6 * model.rbar_throat, 3), ntr=len(xt),
                                 nrp=pnrp, tab=ptab))
    # summary
    ntr = len(xt)
    info = dict(summary=s, files={}, args=vars(a))
    info["table"] = dict(rows=len(tab.rbar), drbar=tab.dr, rbar_last=float(tab.rbar[-1]),
                         breaks=tab.breaks, exterior=tab.exterior)
    info["particles"] = dict(n_total=int(len(m)), n_tracers=ntr, n_dust=int(len(md)), hp=a.hp,
                             dust_mass_lattice=float(md.sum()), dust_mass_continuum=float(model.Mtot - model.M),
                             rel_diff=float(md.sum() / (model.Mtot - model.M) - 1.0),
                             traj_ntrack=ntr)
    info["tracers"] = [dict(index=i, R0=float(Rt[i]), rbar0=float(rbt[i]), m=float(mt[i]), E=float(Et[i]),
                            tags=[i * 14, i * 14 + 13], fate=("falls into the black hole" if Et[i] < -1e-12
                                                               else "marginally bound, expands"))
                       for i in range(len(Rt))]
    for p in (ptab, pnrp, pref, pin):
        info["files"][os.path.basename(p)] = sha256(p)
    with open(os.path.join(a.out, "es.json"), "w") as fo:
        json.dump(info, fo, indent=1, default=float)
    print(json.dumps(dict(summary=s, particles=info["particles"], table=info["table"]), indent=1, default=float))
    if not a.no_figs:
        fig_profiles(model, os.path.join(FIGS, "es_profiles"))
        fig_expansions(model, os.path.join(FIGS, "es_expansions"))
        fig_reference(model, cols, Rt, os.path.join(FIGS, "es_reference"))
        fig_particles(model, xd, md, a.hp, os.path.join(FIGS, "es_particles"))


if __name__ == "__main__":
    main()
