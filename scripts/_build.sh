#!/usr/bin/env bash
# Shared configure+build logic for build_gpu.sh and build_cpu.sh. Not meant to be run
# directly: usage is  _build.sh <gpu|cpu> [build_dir]
#
# Environment (all optional):
#   PROBLEM=<path under athenak/src/pgen, no .cpp>   user pgen (-DPROBLEM); default: the
#            built-in pgens selected at run time by <problem> pgen_name
#   DEBUG=1      Kokkos debug mode + bounds checking (+ -lineinfo on GPU)
#   JOBS=N       parallel compile jobs, capped at 16 (default 16)
#   CUDA_HOME    CUDA toolkit for the GPU build (default /usr/local/cuda-12.6)
#   HOST_ARCH    Kokkos host arch (default ICX = Ice Lake Xeon, matches anta's 8360Y)
#   CMAKE_EXTRA  extra arguments passed verbatim to cmake
#   RECONFIGURE=1  force re-running cmake even if the build dir is already configured
#   ATHENAK_SRC  AthenaK source tree to build (default: <repo>/athenak), e.g. a snapshot
#                made with  git archive HEAD athenak | tar -x -C /some/dir
set -euo pipefail

kind=${1:?usage: _build.sh <gpu|cpu> [build_dir]}
shift

REPO=$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)
SRC=$(cd "${ATHENAK_SRC:-$REPO/athenak}" && pwd)
PROBLEM=${PROBLEM:-built_in_pgens}
DEBUG=${DEBUG:-0}
JOBS=${JOBS:-16}
HOST_ARCH=${HOST_ARCH:-ICX}
CMAKE_EXTRA=${CMAKE_EXTRA:-}
if (( JOBS > 16 )); then JOBS=16; fi

if [[ ! -f $SRC/kokkos/CMakeLists.txt ]]; then
  echo "ERROR: $SRC/kokkos is empty; run: git -C $REPO submodule update --init" >&2
  exit 1
fi
if [[ $PROBLEM != built_in_pgens && ! -f $SRC/src/pgen/$PROBLEM.cpp ]]; then
  echo "ERROR: PROBLEM=$PROBLEM but $SRC/src/pgen/$PROBLEM.cpp does not exist" >&2
  exit 1
fi

# Default build directory: build_<kind>, with suffixes for a user pgen and for DEBUG, so
# that switching PROBLEM or DEBUG never forces a full rebuild of another configuration
# (config.hpp, which carries USER_PROBLEM_ENABLED, is included by every source file).
if [[ $# -ge 1 && -n $1 ]]; then
  BUILD_DIR=$1
else
  BUILD_DIR=$REPO/build_$kind
  if [[ $PROBLEM != built_in_pgens ]]; then BUILD_DIR+="-$(basename "$PROBLEM")"; fi
  if [[ $DEBUG == 1 ]]; then BUILD_DIR+="-debug"; fi
fi
mkdir -p "$BUILD_DIR"
BUILD_DIR=$(cd "$BUILD_DIR" && pwd)

if [[ $DEBUG == 1 ]]; then KDBG=ON; else KDBG=OFF; fi

args=(
  -S "$SRC" -B "$BUILD_DIR"
  -G "Unix Makefiles"
  -DPROBLEM="$PROBLEM"
  -DAthena_ENABLE_MPI=OFF
  -DAthena_ENABLE_OPENMP=OFF
  -DKokkos_ARCH_"$HOST_ARCH"=ON
  -DKokkos_ENABLE_DEBUG=$KDBG
  -DKokkos_ENABLE_DEBUG_BOUNDS_CHECK=$KDBG
  # Do NOT pass Kokkos_ENABLE_DEBUG_DUALVIEW_MODIFY_CHECK: Kokkos 4.7 always enables it,
  # and an explicit OFF is force-flipped to ON on the *next* configure, which rewrites
  # KokkosCore_config.h and triggers a full rebuild after the first CMakeLists.txt edit.
)

if [[ $kind == gpu ]]; then
  CUDA_HOME=${CUDA_HOME:-/usr/local/cuda-12.6}
  if [[ ! -x $CUDA_HOME/bin/nvcc ]]; then
    echo "ERROR: no nvcc in CUDA_HOME=$CUDA_HOME" >&2
    exit 1
  fi
  # Pin the toolkit for every compile, including a bare 'make' run later in the build
  # directory: nvcc_wrapper otherwise calls whatever 'nvcc' is first in PATH (13.2 here).
  WRAP=$BUILD_DIR/nvcc_wrapper_pinned
  # Keep the wrapper byte-identical across re-runs so CMake does not see a new compiler.
  cat > "$WRAP.tmp" <<EOF
#!/bin/sh
# generated by scripts/_build.sh: pins the CUDA toolkit used by kokkos/bin/nvcc_wrapper
CUDA_ROOT=$CUDA_HOME
NVCC_WRAPPER_DEFAULT_COMPILER=g++
export CUDA_ROOT NVCC_WRAPPER_DEFAULT_COMPILER
exec "$SRC/kokkos/bin/nvcc_wrapper" "\$@"
EOF
  if [[ -f $WRAP ]] && cmp -s "$WRAP" "$WRAP.tmp"; then
    rm -f "$WRAP.tmp"
  else
    mv "$WRAP.tmp" "$WRAP"
    chmod +x "$WRAP"
  fi
  if [[ -f $BUILD_DIR/CMakeCache.txt ]] && \
     ! grep -q "^CMAKE_CXX_COMPILER:[A-Z]*=$WRAP\$" "$BUILD_DIR/CMakeCache.txt"; then
    echo "ERROR: $BUILD_DIR was configured with a different compiler; remove it first" >&2
    exit 1
  fi
  if [[ $DEBUG == 1 ]]; then
    BUILD_TYPE=RelWithDebInfo
    FLAGS_VAR=CMAKE_CXX_FLAGS_RELWITHDEBINFO
    FLAGS="-O2 -g -lineinfo"
  else
    BUILD_TYPE=Release
    FLAGS_VAR=CMAKE_CXX_FLAGS_RELEASE
    FLAGS="-O3 -DNDEBUG"
  fi
  args+=(
    -DCMAKE_CXX_COMPILER="$WRAP"
    -DCUDAToolkit_ROOT="$CUDA_HOME"
    -DKokkos_ENABLE_SERIAL=ON
    -DKokkos_ENABLE_CUDA=ON
    -DKokkos_ARCH_AMPERE80=ON
    -DCMAKE_BUILD_TYPE=$BUILD_TYPE
    -D$FLAGS_VAR="$FLAGS"
  )
  toolchain="nvcc $("$CUDA_HOME/bin/nvcc" --version | sed -n 's/.*release \([0-9.]*\).*/\1/p') (host g++ $(g++ -dumpfullversion))"
else
  # Serial CPU build for debugging: -O2 -g, asserts kept (no -DNDEBUG).
  args+=(
    -DCMAKE_CXX_COMPILER=g++
    -DCMAKE_C_COMPILER=gcc
    -DKokkos_ENABLE_SERIAL=ON
    -DKokkos_ENABLE_CUDA=OFF
    -DCMAKE_BUILD_TYPE=RelWithDebInfo
    -DCMAKE_CXX_FLAGS_RELWITHDEBINFO="-O2 -g"
  )
  toolchain="g++ $(g++ -dumpfullversion), Kokkos Serial"
fi
# shellcheck disable=SC2206
args+=( $CMAKE_EXTRA )

log=$BUILD_DIR/build.log
t0=$(date +%s)
{
  echo "=== $(date '+%F %T') build $kind in $BUILD_DIR"
  echo "    PROBLEM=$PROBLEM DEBUG=$DEBUG JOBS=$JOBS toolchain: $toolchain"
} | tee "$log"

# Re-run cmake only when needed: first configure, a change of the options above, or
# RECONFIGURE=1. Edits to athenak/src/CMakeLists.txt are picked up by make itself.
stamp=$BUILD_DIR/.configure_args
want=$(printf '%s\n' "${args[@]}")
if [[ ! -f $BUILD_DIR/Makefile || ! -f $stamp || ${RECONFIGURE:-0} == 1 ]] || \
   [[ "$(cat "$stamp")" != "$want" ]]; then
  rm -f "$stamp"
  cmake "${args[@]}" 2>&1 | tee -a "$log"
  [[ ${PIPESTATUS[0]} -eq 0 ]] || { echo "ERROR: cmake failed, see $log" >&2; exit 1; }
  printf '%s\n' "$want" > "$stamp"
fi

set +e
cmake --build "$BUILD_DIR" --parallel "$JOBS" 2>&1 | tee -a "$log"
rc=${PIPESTATUS[0]}
set -e
t1=$(date +%s)
if [[ $rc -ne 0 ]]; then
  echo "ERROR: build failed (exit $rc) after $((t1-t0)) s; first errors:" >&2
  grep -n -m 20 -E "error|Error" "$log" >&2 || true
  exit $rc
fi

EXE=$BUILD_DIR/src/athena
echo "=== build finished in $((t1-t0)) s  ($toolchain, PROBLEM=$PROBLEM, DEBUG=$DEBUG)" \
  | tee -a "$log"
echo "$EXE"
